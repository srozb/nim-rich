## Port of `nim_rich/unicode_data` — port of `rich._unicode_data`.
##
## `rich._unicode_data` is a private package that loads Unicode
## East-Asian-Width cell tables for `rich.cells`.
## `rich/_unicode_data/__init__.py` exposes `load(version)` (`@cache`,
## __init__.py:58-93) and `VERSIONS` (re-exported from `_versions.py`,
## __init__.py:15). `rich.cells` binds `load` as `load_cell_table`
## (cells.py:7) and uses `CellTable.widths` / `CellTable.narrow_to_wide`
## to compute cell sizes (cells.py:47-…).
##
## This module PERSISTS the required Unicode 15.1 cell table directly
## (no generator/extractor; the data below is the verbatim port of
## `rich/_unicode_data/unicode15-1-0.py`). Per the task contract, the 15.1
## table is embedded  (the latest rich 15.0.0 table is 17.0.0;
## the `load`/`loadCellTable` body — which resolves `"auto"`/`"latest"`/a
## specific version to a table — lives in `cells.nim` (it returns the
## cells-owned `CellTable`); this module provides the raw 15.1 data consts and
## `parseVersion`, the persisted input `cells.loadCellTable` builds upon).
##
## `CellTable`/`CellSpan` are owned by `cells.nim` (matching Python
## `rich.cells`, where `CellSpan`/`CellTable` live in `rich/cells.py`); this
## module is a pure DATA carrier. It persists the raw width table as
## anonymous `(int, int, int)` tuples (`widths15_1`), the `narrowToWide15_1`
## sequence, the version registry, and `parseVersion`, and does NOT import
## `cells` -- so there is no cells<->unicode_data import cycle. `cells`
## builds the `CellTable` from this data and self-installs its loader.
## `std/sets` provides `toHashSet` for `versionSet` (the `frozenset` -> `HashSet`
## mirror of `VERSION_SET`, __init__.py:28).
##
## Naming: `load`->`loadCellTable` (the `load_cell_table` alias used by
## cells, cells.py:7); `_parse_version`->`parseVersion`;
## `VERSIONS`->`versions`; `VERSION_ORDER`->`versionOrder`;
## `VERSION_SET`->`versionSet`. The 15.1 data is suffixed `_15_1`
## (`unicodeVersion15_1`/`widths15_1`/`narrowToWide15_1`) since per-version
## tables will coexist. `CellSpan` fields (`start`, `endIdx`, `cellSize`)
## match `cells.nim` (`end`->`endIdx`, Nim keyword). Proc bodies are Phase
## 0 stubs (`discard`); the data consts are real persisted data (not stubs).

